"""Builds docs/reference/settings.md: every environment variable, from the field docs.

The description of a variable is, in this order: `Field(description=...)`, the string
under the field (an attribute docstring), the `#` comment lines right above the field,
then its trailing `#` comment. `scripts/settings_reference.py` writes the file and a
test fails when the file is out of date.
"""

import ast
import inspect
import io
import textwrap
import tokenize
from dataclasses import dataclass
from enum import Enum
from pathlib import Path
from types import NoneType, UnionType
from typing import Any, Literal, Union, get_args, get_origin

from app.settings import Settings
from app.shared.ai_tasks import TASK_SPECS, AiTask
from app.shared.paths import BACKEND_ROOT

from pydantic import BaseModel, SecretStr
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

REFERENCE_PATH = BACKEND_ROOT.parent / "docs" / "reference" / "settings.md"
REGENERATE = "cd backend && uv run python scripts/settings_reference.py"
NO_VALUE = "-"

INTRO = """\
# Settings reference

Generated by `{regenerate}`; do not edit by hand. The source is `app/settings.py`,
`app/settings_ai.py` and `app/settings_features.py`: change a field or its comment
there and run the script again (a test fails while this file is out of date).

## How settings are read

- Every variable starts with `IHSP_`; a nested section is separated by `__`:
  `IHSP_DATABASE__POOL_SIZE=20` sets `settings.database.pool_size`.
- Order of precedence, highest first: the process environment, the last file of
  `IHSP_ENV_FILE`, the earlier files, the defaults in the code.
- `IHSP_ENV_FILE` is a comma list of dotenv files and layers them:
  `IHSP_ENV_FILE=materials/dev.env,.env.local` reads `dev.env` first and lets
  `.env.local` override it. A `?` before a name (`?.env.local`) makes the file
  optional; a required file that does not exist stops the start.
- An empty value (`IHSP_X=`) means "not set".
- A bad value stops the start with one line per variable, for example
  `IHSP_AI__DEFAULT__TEMPERATURE: Input should be a valid number (got 'hot')`.
  An `IHSP_` variable that is no setting (a typo) is logged as a warning.
- Lists are comma separated (`a,b`); a JSON list also works.
- Development defaults match `materials/dev.env`; in production
  (`IHSP_ENV=prod`) the app refuses the development secrets.

## AI models per task

Each place that calls a language model is an AI task (the table below). Modules ask
for a task and never for a model name; the settings decide what the task runs with:

```
IHSP_AI__DEFAULT__MODEL=anthropic/claude-haiku-4.5      # every task without its own
IHSP_AI__DEFAULT__TEMPERATURE=0.2
IHSP_AI__TASKS__STUDIO_QUIZ__MODEL=anthropic/claude-sonnet-5.5
IHSP_AI__TASKS__STUDIO_QUIZ__FALLBACKS=anthropic/claude-haiku-4.5
IHSP_AI__TASKS__STUDENT_CHAT_SMART__BUDGET_WEIGHT=4
```

A task takes its own `AI__TASKS__<TASK>__<FIELD>`, else the value the code gives that
task (the smart tier ships with a larger model and weight 4; notebook tasks send
`data_collection: deny`), else `AI__DEFAULT__<FIELD>`.

{tasks}
"""

DEPRECATED = "Deprecated"


@dataclass(frozen=True, slots=True)
class Row:
    """One environment variable."""

    variable: str
    type: str
    default: str
    description: str


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _comment_rows(source: str) -> dict[int, str]:
    """Trailing comments by line number (a comment after code, not on its own line)."""
    found: dict[int, str] = {}
    lines = source.splitlines()
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        row, col = token.start
        if token.type == tokenize.COMMENT and lines[row - 1][:col].strip():
            found[row] = token.string.lstrip("#").strip()
    return found


def _leading_comment(lines: list[str], first_line: int) -> str:
    """The `#` lines directly above a field (1-based `first_line`), joined."""
    found: list[str] = []
    index = first_line - 2
    while index >= 0 and lines[index].strip().startswith("#"):
        found.append(lines[index].strip().lstrip("#").strip())
        index -= 1
    return " ".join(reversed(found))


def _docstring_after(body: list[ast.stmt], index: int) -> str | None:
    if index + 1 >= len(body):
        return None
    node = body[index + 1]
    if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant):
        if isinstance(node.value.value, str):
            return " ".join(inspect.cleandoc(node.value.value).split())
    return None


def field_docs(model: type[BaseModel]) -> dict[str, str]:
    """Descriptions of the fields of a settings class, read from its source."""
    try:
        source = textwrap.dedent(inspect.getsource(model))
    except (OSError, TypeError):  # pragma: no cover - no source available
        return {}
    cls = ast.parse(source).body[0]
    if not isinstance(cls, ast.ClassDef):  # pragma: no cover
        return {}
    lines, trailing = source.splitlines(), _comment_rows(source)
    docs: dict[str, str] = {}
    for index, node in enumerate(cls.body):
        if not (isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)):
            continue
        end = node.end_lineno or node.lineno
        side = [trailing[n] for n in range(node.lineno, end + 1) if n in trailing]
        text = _docstring_after(cls.body, index) or " ".join(
            part for part in (_leading_comment(lines, node.lineno), *side) if part
        )
        docs[node.target.id] = text
    return docs


def type_name(annotation: Any) -> str:  # a pydantic annotation
    """A short, readable type for the table."""
    origin = get_origin(annotation)
    args = [arg for arg in get_args(annotation) if arg is not NoneType]
    if origin is Literal:
        return " | ".join(str(arg) for arg in args)
    if origin in (UnionType, Union):
        return " | ".join(type_name(arg) for arg in args)
    if origin in (tuple, list):
        return f"list of {type_name(args[0])}"
    if isinstance(annotation, type) and issubclass(annotation, Enum):
        return " | ".join(str(member.value) for member in annotation)
    if annotation is SecretStr:
        return "secret"
    return getattr(annotation, "__name__", str(annotation))


def default_text(field: FieldInfo) -> str:
    """The default as the table shows it; development secrets are not printed."""
    value = field.get_default(call_default_factory=True)
    if value is PydanticUndefined:
        return "required"
    if isinstance(value, SecretStr):
        return "(development value)" if value.get_secret_value() else NO_VALUE
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, tuple | list):
        return (
            ("`" + ",".join(str(item) for item in value) + "`") if value else NO_VALUE
        )
    if value is None or value == "":
        return NO_VALUE
    return f"`{value}`"


def _model_of(annotation: Any) -> type[BaseModel] | None:  # a pydantic annotation
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    return None


def _key_placeholder(key_type: Any) -> str:  # a pydantic annotation
    name = getattr(key_type, "__name__", "key")
    return "<" + (name.removeprefix("Ai") or name).upper() + ">"


def collect(model: type[BaseModel], prefix: str = "") -> list[Row]:
    """Rows of a settings class and everything nested in it, in field order."""
    docs = field_docs(model)
    rows: list[Row] = []
    for name, field in model.model_fields.items():
        variable = f"{prefix}{name.upper()}"
        annotation = field.annotation
        if get_origin(annotation) is dict:
            key_type, annotation = get_args(annotation)
            variable += f"__{_key_placeholder(key_type)}"
        section = _model_of(annotation)
        if section is not None:
            rows.extend(collect(section, f"{variable}__"))
            continue
        description = field.description or docs.get(name, "")
        rows.append(
            Row(variable, type_name(annotation), default_text(field), description)
        )
    return rows


def _table(rows: list[Row]) -> str:
    lines = [
        "| Variable | Type | Default | Description |",
        "|---|---|---|---|",
    ]
    for row in rows:
        cells = (f"`IHSP_{row.variable}`", row.type, row.default, row.description)
        lines.append("| " + " | ".join(_cell(cell) for cell in cells) + " |")
    return "\n".join(lines)


def _tasks_table() -> str:
    lines = ["| `<TASK>` | Group | What it does |", "|---|---|---|"]
    for task in AiTask:
        spec = TASK_SPECS[task]
        lines.append(
            f"| `{task.value.upper()}` | {spec.group} | {_cell(spec.summary)} |"
        )
    return "\n".join(lines)


def _section(title: str, intro: str, rows: list[Row]) -> str:
    return f"## {title}\n\n{intro}\n\n{_table(rows)}\n"


def _sections() -> list[str]:
    blocks: list[str] = []
    docs = field_docs(Settings)
    root = [
        Row(
            name.upper(),
            type_name(field.annotation),
            default_text(field),
            field.description or docs.get(name, ""),
        )
        for name, field in Settings.model_fields.items()
        if _model_of(field.annotation) is None
    ]
    blocks.append(_section("Root", "Process-wide settings.", root))
    for name, field in Settings.model_fields.items():
        section = _model_of(field.annotation)
        if section is None:
            continue
        intro = " ".join((inspect.getdoc(section) or "").split("\n\n")[0].split())
        blocks.append(
            _section(
                f"`IHSP_{name.upper()}__*`",
                intro,
                collect(section, f"{name.upper()}__"),
            )
        )
    return blocks


def _deprecated(rows: list[Row]) -> str:
    old = [row for row in rows if row.description.startswith(DEPRECATED)]
    return "## Deprecated variables\n\nStill read, with a warning in the log.\n\n" + (
        _table(old)
    )


def render() -> str:
    """The whole reference file."""
    header = INTRO.format(regenerate=REGENERATE, tasks=_tasks_table())
    rows = collect(Settings)
    return header + "\n" + "\n".join(_sections()) + "\n" + _deprecated(rows) + "\n"


def write(path: Path = REFERENCE_PATH) -> Path:
    """Write the reference and return its path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(), encoding="utf-8")
    return path
